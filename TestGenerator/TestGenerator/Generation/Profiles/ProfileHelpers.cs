using System.Collections.Generic;
using System.Linq;
using TestGenerator.Linking;

namespace TestGenerator.Generation.Profiles;

internal static class ProfileHelpers
{
    public static void Header(CodeWriter w, GenerationOptions options, IEnumerable<string> usings)
    {
        w.Line("// <auto-generated/>");
        w.Line($"// TestGenerator {options.ToolVersion}");
        w.Line("#nullable enable annotations");
        foreach (var u in usings.Distinct().OrderBy(u => u))
        {
            w.Line($"using {u};");
        }
        w.Line();
    }

    public static void Traits(CodeWriter w, TestIntent intent)
    {
        w.Line($"[Trait(\"TestGen\", {CSharp.Literal(intent.Id)})]");
        w.Line($"[Trait(\"TestGenStatus\", \"{intent.Status}\")]");
    }

    public static void CreateTraits(CodeWriter w, EntityTestPlan plan)
    {
        w.Line($"[Trait(\"TestGen\", \"{plan.Name}.Create\")]");
        w.Line("[Trait(\"TestGenStatus\", \"CodeOnly\")]");
    }

    public static string SkipAttribute(string kind, string? reason) =>
        reason == null ? $"[{kind}]" : $"[{kind}(Skip = {CSharp.Literal(reason)})]";

    public static string ValueExpression(StringTestPlan test) =>
        $"length < 0 ? null! : {test.Shape.OfLengthExpression("length")}";

    public static void InlineCases(CodeWriter w, StringTestPlan test)
    {
        foreach (var (length, shouldThrow) in test.Cases())
        {
            w.Line($"[InlineData({length}, {(shouldThrow ? "true" : "false")})]");
        }
    }

    public static void MissingMember(CodeWriter w, EntityTestPlan plan, MissingMemberPlan member)
    {
        Traits(w, member.Intent);
        w.Open($"public void Member_{plan.Name}_{member.ExpectedName}_Exists()");
        w.Line($"typeof({plan.Name}).GetProperty({CSharp.Literal(member.ExpectedName)})");
        w.Line($"    .ShouldNotBeNull({CSharp.Literal(member.Intent.Message)});");
        w.Close();
        w.Line();
    }
}
